const normalize = (text: string) =>
  text
    .trim()
    .replace(/[:：…]+$|\.{3}$/g, "")
    .trim()
    .toLowerCase();

const byEnglish = new Map<string, GlossaryEntry>();
for (const entry of GLOSSARY) {
  const key = normalize(entry.en);
  if (!byEnglish.has(key)) byEnglish.set(key, entry);
}

/** Look up a glossary term by its English text. */
export function glossaryLookup(english: string): GlossaryEntry | undefined {
  return byEnglish.get(normalize(english));
}

/** True when `arabic` is an accepted rendering of the glossary term. */
export function matchesGlossary(entry: GlossaryEntry, arabic: string): boolean {
  const strip = (s: string) => s.trim().replace(/[:：…]+$|\.{3}$/g, "").trim();
  const candidate = strip(arabic);
  return [entry.ar, ...(entry.alt ?? [])].some((accepted) => strip(accepted) === candidate);
}
