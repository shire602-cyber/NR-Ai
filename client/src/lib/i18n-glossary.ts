/**
 * English -> Arabic glossary for the accounting / UAE tax vocabulary.
 *
 * SINGLE SOURCE OF TRUTH for terminology. Every per-page message table
 * (`*.i18n.ts`) is checked against this list by a unit test: if the English
 * text of a message equals a glossary term (case-insensitive, ignoring a
 * trailing colon/ellipsis), its Arabic must be the glossary Arabic or one of
 * the accepted `alt` forms (grammatical variants: gender, definiteness, plural).
 *
 * Terminology follows the UAE Federal Tax Authority (FTA) Arabic publications
 * and UAE bank statements. Where the product already used two different Arabic
 * words for one thing, the chosen standard is noted in a `// STANDARD:` comment.
 *
 * Not translated on purpose: product name (Muhasib.ai), currency codes (AED,
 * USD), TRN/IBAN/SWIFT values, "WhatsApp"/"Excel"/"PDF"/"CSV" file and brand
 * names, e-mail addresses.
 */

export interface GlossaryEntry {
  readonly en: string;
  readonly ar: string;
  /** Other accepted Arabic renderings (gender/number/definiteness variants). */
  readonly alt?: readonly string[];
}

const g = (en: string, ar: string, ...alt: string[]): GlossaryEntry => ({ en, ar, alt });

