/** True when `pathname` belongs to the signed-in app (sign-in required, not a 404). */
export function isAppSectionPath(pathname: string): boolean {
  const first = pathname.split("?")[0].split("/")[1] ?? "";
  return APP_SECTIONS.has(first);
}
