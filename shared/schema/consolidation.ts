export const companyGroups = pgTable(
  "company_groups",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`gen_random_uuid()`),
    name: text("name").notNull(),
    parentCompanyId: uuid("parent_company_id")
      .notNull()
      .references(() => companies.id, { onDelete: "cascade" }),
    reportingCurrency: text("reporting_currency").notNull().default("AED"),
    createdBy: uuid("created_by").references(() => users.id, { onDelete: "set null" }),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at"),
  },
  (table) => ({
    parentIdx: index("idx_company_groups_parent").on(table.parentCompanyId),
  })
);
export type CompanyGroup = typeof companyGroups.$inferSelect;

export const companyGroupMembers = pgTable(
  "company_group_members",
  {
    id: uuid("id")
      .primaryKey()
      .default(sql`gen_random_uuid()`),
    groupId: uuid("group_id")
      .notNull()
      .references(() => companyGroups.id, { onDelete: "cascade" }),
    companyId: uuid("company_id")
      .notNull()
      .references(() => companies.id, { onDelete: "cascade" }),
    ownershipPercent: vatRateType("ownership_percent").notNull().default(1), // fraction 0..1
    method: text("method").notNull().default("full"), // full | none
    effectiveFrom: pgDate("effective_from", { mode: "string" }),
    effectiveTo: pgDate("effective_to", { mode: "string" }),
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  (table) => ({
    groupCompanyUnique: uniqueIndex("uq_company_group_members_group_company").on(
      table.groupId,
      table.companyId
    ),
    companyIdx: index("idx_company_group_members_company").on(table.companyId),
  })
);
export type CompanyGroupMember = typeof companyGroupMembers.$inferSelect;

