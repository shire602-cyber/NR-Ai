/** int8 integer minor units (fils / cents of the group reporting currency). */
const w5cMinor = customType<{ data: number; driverData: string | number }>({
  dataType() {
    return "bigint";
  },
  fromDriver(value: string | number): number {
    return Number(value);
  },
  toDriver(value: number) {
    return String(Math.trunc(value));
  },
});

