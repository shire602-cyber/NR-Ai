const patterns = SPA_PATHS.map((path) => path.toLowerCase().split("/"));

export function isSpaPath(path: string): boolean {
  if (path === "/__ui") return process.env.VITE_UI_GALLERY === "1";
  const segments = path.toLowerCase().split("/");
  return patterns.some(
    (pattern) =>
      pattern.length === segments.length &&
      pattern.every((part, index) =>
        part.startsWith(":") ? Boolean(segments[index]) : part === segments[index]
      )
  );
}
